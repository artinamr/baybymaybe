"""Work covers: a 1200 px copy of each card cover (srcset) and a tiny blurred
preview (shown behind the card while its cover loads), written to
content/coverPreviews.ts. Run from the repo root after the covers change:
    python tools/qa/coverprev.py
"""
import base64
import io
import os
from PIL import Image, ImageFilter

SRC = "public/work"
NAMES = ["practice-website", "operations-portal", "enquiry-desk", "butter-days", "blackridge", "outbound"]

lines = []
for name in NAMES:
    im = Image.open(os.path.join(SRC, f"{name}.webp")).convert("RGB")
    w = 1200
    h = round(im.height * w / im.width)
    im.resize((w, h), Image.LANCZOS).save(os.path.join(SRC, f"{name}-1200.webp"), "WEBP", quality=80, method=6)
    # The preview: 32 px wide, softened, low quality; the browser scales it up
    # blurred behind the card.
    pw = 32
    ph = round(im.height * pw / im.width)
    small = im.resize((pw, ph), Image.LANCZOS).filter(ImageFilter.GaussianBlur(0.6))
    buf = io.BytesIO()
    small.save(buf, "WEBP", quality=45, method=6)
    uri = "data:image/webp;base64," + base64.b64encode(buf.getvalue()).decode()
    lines.append(f'  "{name}": "{uri}",')
    print(name, os.path.getsize(os.path.join(SRC, f"{name}-1200.webp")), "bytes at 1200;", len(uri), "chars preview")

with open("content/coverPreviews.ts", "w", encoding="utf-8", newline="\n") as f:
    f.write("/**\n * Generated by tools/qa/coverprev.py (do not edit): a tiny blurred preview of\n")
    f.write(" * each work cover, shown behind its card while the cover loads. Each cover\n")
    f.write(" * also has a 1200 px copy beside it (<name>-1200.webp) for srcset.\n */\n")
    f.write("export const COVER_PREVIEW: Record<string, string> = {\n")
    f.write("\n".join(lines) + "\n};\n")
print("wrote content/coverPreviews.ts")
